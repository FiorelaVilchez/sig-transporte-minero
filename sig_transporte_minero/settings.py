# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases
#
# Motor seleccionable por variables de entorno (RNF-04):
#   - Si DB_ENGINE=postgresql en .env → usa PostgreSQL (vía psycopg2-binary)
#   - Si DB_ENGINE no está definida    → usa SQLite por defecto (desarrollo local rápido)

#   - Si existe DATABASE_URL (servicios en la nube como Render) → tiene prioridad

_DB_ENGINE = config('DB_ENGINE', default='sqlite')
_DATABASE_URL = config('DATABASE_URL', default='')

if _DATABASE_URL:
    DATABASES = {
        'default': dj_database_url.parse(
            _DATABASE_URL,
            conn_max_age=config('DB_CONN_MAX_AGE', default=60, cast=int),
            conn_health_checks=True,
        )
    }
elif _DB_ENGINE == 'postgresql':
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': config('DB_NAME', default='sig_transporte_minero'),
            'USER': config('DB_USER', default='postgres'),
            'PASSWORD': config('DB_PASSWORD', default=''),
            'HOST': config('DB_HOST', default='127.0.0.1'),
            'PORT': config('DB_PORT', default='5432'),
            # Reutiliza la conexión entre peticiones: en Windows, PostgreSQL crea un
            # proceso por cada conexión nueva y eso hacía lenta cada página.
            'CONN_MAX_AGE': config('DB_CONN_MAX_AGE', default=60, cast=int),
            'CONN_HEALTH_CHECKS': True,
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


